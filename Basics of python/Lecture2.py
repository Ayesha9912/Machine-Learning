# there are three types of data types in python
# . Basic type - (int, float, bool, str)
# . container type - (list , tuple, set, dict)
# . User defined type - (class, object)


#integer
print(10)
print(1e309) #infinite

#float
print(10.5)


#boolean
print(True)
print(False)

#complex
print(1+2j)

#string
print('Hello World')
print("Hello World")
print("""Hello World""")

#list - square brackets
print([1, 2, 3, 4, 5])


#tuple - small brackets
print((1, 2, 3, 4, 5))

#set - curly brackets
print({1, 2, 3, 4, 5})

#dict - curly brackets
print({1: "one", 2: "two", 3: "three"})
