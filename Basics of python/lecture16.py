#built-in function
#print() function is used to print the output on the screen.
#input() function is used to take input from the user.
input("Enter your name: ")

#type() function is used to check the data type of a variable.
type(10)

#int() function is used to convert a string to an integer.
int("10")

#abs() function is used to return the absolute value of a number.
abs(-10) #modulus operator

#pow() function is used to return the value of a number raised to the power of another number.
pow(2, 3) #2^3 = 8

#min/max() function is used to return the minimum/maximum value from a list of numbers.
min(1, 2, 3, 4, 5) #1
max(1, 2, 3, 4, 5) #5

#round() function is used to round a number to the nearest integer.
round(3.6) #4

#divmod() function is used to return the quotient and remainder of a division operation.
divmod(10, 3) #(3, 1) - quotient and remainder

#bin/oct/hex() function is used to convert a decimal number to binary/octal/hexadecimal.
bin(10) #0b1010
oct(10) #0o12
hex(10) #0xa


#id() function is used to return the unique id of an object.
id(10) #140711168


#ord() function is used to return the ASCII value of a character.
ord("A") #65
ord("a") #97


#len() function is used to return the length of a string.
len("Hello") #5
len([1, 2, 3, 4, 5]) #5

#sum() function is used to return the sum of all the elements in a list.
sum([1, 2, 3, 4, 5]) #15

#help() function is used to return the documentation of a function.
help(print) #print() function is used to print the output on the screen.